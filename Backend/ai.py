"""API-based AI generation supporting OpenAI, Google Gemini, and OpenAI-compatible APIs (Groq, OpenRouter, DeepSeek)."""
import json
import os
import urllib.error
import urllib.request
from dotenv import load_dotenv

load_dotenv()


def _call_openai(api_key: str, base_url: str, model: str, system: str, prompt: str, max_tokens: int) -> str:
    url = f"{base_url.rstrip('/')}/chat/completions"
    payload = {
        "model": model,
        "messages": [
            {"role": "system", "content": system},
            {"role": "user", "content": prompt},
        ],
        "max_tokens": max(max_tokens, 1200),
    }
    data = json.dumps(payload).encode("utf-8")
    req = urllib.request.Request(
        url,
        data=data,
        headers={
            "Content-Type": "application/json",
            "Authorization": f"Bearer {api_key}",
            "User-Agent": "MealPlanner/1.0",
        },
    )
    with urllib.request.urlopen(req, timeout=45) as resp:
        res = json.loads(resp.read().decode("utf-8"))
        return res["choices"][0]["message"]["content"]


def _call_gemini(api_key: str, model: str, system: str, prompt: str, max_tokens: int) -> str:
    # Try preferred model first, then fallback to current stable Gemini models
    models_to_try = [model]
    for fallback in ["gemini-3.5-flash-lite", "gemini-3.5-flash", "gemini-3.1-flash-lite", "gemini-flash-latest"]:
        if fallback not in models_to_try:
            models_to_try.append(fallback)

    last_error = None
    for m in models_to_try:
        url = f"https://generativelanguage.googleapis.com/v1beta/models/{m}:generateContent?key={api_key}"
        payload = {
            "contents": [
                {
                    "role": "user",
                    "parts": [{"text": f"System Instructions:\n{system}\n\nTask:\n{prompt}"}],
                }
            ],
            "generationConfig": {
                "maxOutputTokens": max(max_tokens, 1500),
            },
        }
        data = json.dumps(payload).encode("utf-8")
        req = urllib.request.Request(
            url,
            data=data,
            headers={"Content-Type": "application/json"},
        )
        try:
            with urllib.request.urlopen(req, timeout=30) as resp:
                res = json.loads(resp.read().decode("utf-8"))
                candidates = res.get("candidates", [])
                if candidates and "content" in candidates[0]:
                    parts = candidates[0]["content"].get("parts", [])
                    text = "".join(p.get("text", "") for p in parts if "text" in p)
                    if text:
                        return text
                return "No response generated by Gemini."
        except urllib.error.HTTPError as e:
            last_error = e
            if e.code in (404, 503):
                # Model unavailable or high demand; try fallback model
                continue
            raise
        except Exception as e:
            last_error = e
            continue

    if last_error:
        raise last_error
    return "No response generated by Gemini."


def generate(system: str, prompt: str, max_new_tokens: int) -> str:
    # Always reload env so key changes take effect immediately without restarting the server
    load_dotenv(override=True)

    gemini_key = os.getenv("GEMINI_API_KEY", "").strip()
    openai_key = (os.getenv("OPENAI_API_KEY") or os.getenv("AI_API_KEY") or "").strip()

    if not gemini_key and not openai_key:
        return (
            "⚠️ AI API key not found in Backend/.env.\n\n"
            "Please open Backend/.env and set your API key:\n"
            "- For OpenAI: OPENAI_API_KEY=your_key_here\n"
            "- Or for Gemini: GEMINI_API_KEY=your_key_here\n\n"
            "Save the file and click generate again!"
        )

    try:
        if gemini_key:
            model = os.getenv("GEMINI_MODEL") or os.getenv("AI_MODEL") or "gemini-3.5-flash-lite"
            return _call_gemini(gemini_key, model, system, prompt, max_new_tokens)
        else:
            base_url = os.getenv("OPENAI_BASE_URL") or os.getenv("AI_BASE_URL") or "https://api.openai.com/v1"
            model = os.getenv("OPENAI_MODEL") or os.getenv("AI_MODEL") or "gpt-4o-mini"
            return _call_openai(openai_key, base_url, model, system, prompt, max_new_tokens)
    except urllib.error.HTTPError as e:
        err_msg = e.read().decode("utf-8", errors="ignore")
        print(f"[AI HTTP Error {e.code}]: {err_msg}")
        return f"⚠️ AI API returned HTTP {e.code}: {err_msg}"
    except Exception as e:
        print(f"[AI Error]: {e}")
        return f"⚠️ AI API call failed: {str(e)}"
